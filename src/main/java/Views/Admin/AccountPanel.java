    private void initTable() {
        tableModel = new DefaultTableModel();
        tableModel.setColumnIdentifiers(new String[]{"Mã tài khoản", "Tên đăng nhập", "Vai trò"});
        tblAccount.setModel(tableModel);
    }

    private void loadData() {
        List<User> list = controller.getAllAccounts();
        tableModel.setRowCount(0);
        for (User user : list) {
            tableModel.addRow(new Object[]{
                user.getUserID(),
                user.getTen(),
                user.getRole()
            });
        }
    }

    private void setupEventHandlers() {
        tblAccount.getSelectionModel().addListSelectionListener(e -> {
            if (!e.getValueIsAdjusting()) {
                int selectedRow = tblAccount.getSelectedRow();
                if (selectedRow >= 0) {
                    String userId = (String) tableModel.getValueAt(selectedRow, 0);
                    String username = (String) tableModel.getValueAt(selectedRow, 1);
                    String role = (String) tableModel.getValueAt(selectedRow, 2);

                    txtUserId.setText(userId);
                    txtUsername.setText(username);
                    cmbRole.setSelectedItem(role);
                    btnDelete.setEnabled(true);
                }
            }
        });
    }

    private User getAccountFromForm() {
        String userId = txtUserId.getText().trim();
        String username = txtUsername.getText().trim();
        String role = (String) cmbRole.getSelectedItem();
        String password = new String(txtPassword.getPassword());
        String confirmPassword = new String(txtConfirmPassword.getPassword());

        if (username.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Vui lòng nhập tên đăng nhập!", "Lỗi", JOptionPane.ERROR_MESSAGE);
            return null;
        }

        if (password.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Vui lòng nhập mật khẩu!", "Lỗi", JOptionPane.ERROR_MESSAGE);
            return null;
        }

        if (!password.equals(confirmPassword)) {
            JOptionPane.showMessageDialog(this, "Mật khẩu xác nhận không khớp!", "Lỗi", JOptionPane.ERROR_MESSAGE);
            return null;
        }

        // Generate new user ID if it's empty (for new accounts)
        if (userId.isEmpty()) {
            userId = Models.User.generateNewUserId();
        }

        return new User(userId, username, password, role);
    }

    private void clearForm() {
        txtUserId.setText("");
        txtUsername.setText("");
        txtPassword.setText("");
        txtConfirmPassword.setText("");
        cmbRole.setSelectedIndex(0);
        tblAccount.clearSelection();
        btnDelete.setEnabled(false);
    }

